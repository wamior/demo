create table roles (
    id integer generated by default as identity primary key,
    role_name varchar(255) not null unique
);
create table sizes (
    id integer generated by default as identity primary key,
    size numeric(4, 1) not null unique
);
create table users (
    id integer generated by default as identity primary key,
    surname varchar(100) not null,
    name varchar(100) not null,
    patronymic varchar(100) login varchar(255),
    role_id integer,
    foreign key (role_id) references roles(id) on delete restrict
);
create table products (
    id integer generated by default as identity primary key,
    category varchar(255) not null,
    subcategory varchar(255) not null,
    image varchar(255),
    name varchar(255) not null,
    production varchar(255) not null,
    description varchar(255),
    compound varchar(255) not null,
    price numeric(12, 2) check (price >= 0) on delete restrict
);
create table stocks (
    id integer generated by default as identity primary key,
    product_id integer not null,
    size_id integer not null,
    count integer not null,
    foreign key (product_id) references products(id) on delete restrict,
    foreign key (size_id) references sizes(id) on delete restrict
);
create table orders (
    id integer generated by default as identity primary key,
    order_date date not null,
    user_id integer not null,
    foreign key (user_id) references users(id) on delete restrict
);
create table orders_item (
    id integer generated by default as identity primary key,
    order_id integer not null,
    stock_id integer not null,
    quantity integer not null,
    unit_price numeric(14, 2) not null,
    foreign key (order_id) references orders(id) on delete cascade,
    foreign key (stock_id) references stocks(id) on delete restrict
)